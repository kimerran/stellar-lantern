// Generates the Android app's `asset_statements` string resource (#263) from
// the mini-app directory, so adding a dApp doesn't mean editing XML by hand.
//
//   npm run android:assets              # write the resource
//   npm run android:assets -- --check   # fail if the committed file differs
//
// The sites come from deepLinkOrigins() in src/core/miniapps/deep-link.ts —
// the same list "Open in Lantern" links are allowed to open — so what Chrome
// is told about and what the deep link accepts can't drift. A site listed here
// can see Lantern via navigator.getInstalledRelatedApps() once its own web
// manifest names com.lantern.wallet in related_applications.

import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const OUT = join(ROOT, 'android/app/src/main/res/values/asset_statements.xml');
const check = process.argv.includes('--check');

// Bundle the TS module (and its @shared alias) in memory, then import it.
const result = await build({
  entryPoints: [join(ROOT, 'src/core/miniapps/deep-link.ts')],
  bundle: true,
  write: false,
  format: 'esm',
  platform: 'node',
  alias: { '@shared': join(ROOT, 'src/shared') },
  logLevel: 'warning',
});
const src = result.outputFiles[0].text;
const mod = await import(`data:text/javascript;base64,${Buffer.from(src).toString('base64')}`);

const origins = mod.deepLinkOrigins();
const json = mod.assetStatements(origins);

// Android string resources: escape XML, then backslash-escape the quotes and
// apostrophes aapt would otherwise strip or reject.
const escaped = json
  .replace(/&/g, '&amp;')
  .replace(/</g, '&lt;')
  .replace(/>/g, '&gt;')
  .replace(/\\/g, '\\\\')
  .replace(/"/g, '\\"')
  .replace(/'/g, "\\'");

const xml = `<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by scripts/gen-asset-statements.mjs from src/core/miniapps/directory.ts.
     Don't edit: run \`npm run android:assets\`. CI fails if this is stale.
     Sites: ${origins.join(', ') || '(none)'} -->
<resources>
    <string name="asset_statements" translatable="false">${escaped}</string>
</resources>
`;

if (check) {
  let current = '';
  try {
    current = readFileSync(OUT, 'utf8');
  } catch {
    /* missing counts as stale */
  }
  if (current !== xml) {
    console.error(
      'android:assets: android/app/src/main/res/values/asset_statements.xml is stale. Run `npm run android:assets` and commit it.',
    );
    process.exit(1);
  }
  console.log(`android:assets: up to date (${origins.length} site${origins.length === 1 ? '' : 's'}).`);
} else {
  writeFileSync(OUT, xml);
  console.log(`android:assets: wrote ${origins.length} site${origins.length === 1 ? '' : 's'}: ${origins.join(', ')}`);
}
